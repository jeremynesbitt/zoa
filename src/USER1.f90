!       USER FILES

SUBROUTINE USERSURF(I,X,Y,Z,UERROR)
!
   use DATSP1
   use DATHGR
   use DATCFG
   use DATSPD
   use DATSUB
   use DATLEN
   use DATMAI
   use iso_fortran_env, only: real64
   IMPLICIT NONE
   real(real64) RHO,RHO2,C,C2,X,Y,Z,KAPPA,DEN
   INTEGER I
   LOGICAL UERROR
!     THIS IS THE USER-DEFINED SUBROUTINE SURFACE
!     GIVEN SOME X AND Y, THIS ROUTINE RETURNS Z. IT CAN USE SPECIAL SURFACE
!     COEFS, GENERAL PURPOSE STORAGE REGISTERS AND AND OTHER DATA OR
!     INCLUDED SUBROUTINES. THE MAIN PROGRAM DOES ALL NECESSARY ITERATIVE
!     SURFACE INTERSECTION AND SURFACE NORMAL CALCULATIONS FOR THE USER
!     AND DOES THEM RIGOROUSLY AND CORRECTLY UNLIKE THE BAD ROUTINES
!     USED IN CODE-V WHICH ARE LESS THAN WORTHLESS!
!
!     THE APPROPRIATE Z WHICH IT PASSES BACK TO THE CALLING ROUTINE.
!
!     THIS Z VALUE IS ADDED TO ANY EXISTING Z COMPUTED FOR THINGS LIKE
!     CURVATURE AND ASPHERIC DEFORMATIONS IN THE REGULAR LENS DATABASE.
!
   UERROR=.FALSE.
!
   RHO2=((X**2)+(Y**2))
   RHO=DSQRT(RHO2)
   C2=C**2
   C=FTFL01(1,I)+(FTFL01(2,I)*RHO)+&
   &(FTFL01(3,I)*(RHO**2))+(FTFL01(4,I)*(RHO**3))+&
   &(FTFL01(5,I)*(RHO**4))+(FTFL01(6,I)*(RHO**5))+&
   &(FTFL01(7,I)*(RHO**6))+(FTFL01(8,I)*(RHO**7))+&
   &(FTFL01(9,I)*(RHO**8))+(FTFL01(10,I)*(RHO**9))+&
   &(FTFL01(11,I)*(RHO**10))+(FTFL01(12,I)*(RHO**11))+&
   &(FTFL01(13,I)*(RHO**12))+(FTFL01(14,I)*(RHO**13))+&
   &(FTFL01(15,I)*(RHO**14))+(FTFL01(16,I)*(RHO**15))+&
   &(FTFL01(17,I)*(RHO**16))+(FTFL01(18,I)*(RHO**17))+&
   &(FTFL01(19,I)*(RHO**18))+(FTFL01(20,I)*(RHO**19))+&
   &(FTFL01(21,I)*(RHO**20))
   KAPPA=FTFL01(31,R_I)+(FTFL01(32,I)*RHO)+&
   &(FTFL01(33,I)*(RHO**2))+(FTFL01(34,I)*(RHO**3))+&
   &(FTFL01(35,I)*(RHO**4))+(FTFL01(36,I)*(RHO**5))+&
   &(FTFL01(37,I)*(RHO**6))+(FTFL01(38,I)*(RHO**7))+&
   &(FTFL01(39,I)*(RHO**8))+(FTFL01(40,I)*(RHO**9))+&
   &(FTFL01(41,I)*(RHO**10))+(FTFL01(42,I)*(RHO**11))+&
   &(FTFL01(43,I)*(RHO**12))+(FTFL01(44,I)*(RHO**13))+&
   &(FTFL01(45,I)*(RHO**14))+(FTFL01(46,I)*(RHO**15))+&
   &(FTFL01(47,I)*(RHO**16))+(FTFL01(48,I)*(RHO**17))+&
   &(FTFL01(49,I)*(RHO**18))+(FTFL01(50,I)*(RHO**19))+&
   &(FTFL01(51,I)*(RHO**20))
   DEN=(1.0D0-((KAPPA+1.0D0)*C2*RHO2))
   UERROR=.FALSE.
   IF(DEN.LT.0.0D0) THEN
      UERROR=.TRUE.
      Z=0.0D0
      RETURN
   END IF
   Z=(C*RHO2)/(1+DSQRT(DEN))
   RETURN
END
