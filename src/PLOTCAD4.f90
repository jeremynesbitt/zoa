!       FOURTH FILE OF PLOT/CAD ROUTINES

! SUB PLTCHRSH.FOR
SUBROUTINE PLTCHRSH
   use DATHGR
   use DATLEN
   use DATMAI
   use command_utils, only: is_command_query
   use mod_system, only: sys_mode
   use iso_fortran_env, only: real64
   IMPLICIT NONE
   CHARACTER*11 AXMIN,AXMAX,AYMIN,AYMAX,YHIGHH,XHIGHH
   LOGICAL TABEXIST
   real(real64) SHIFT_TABLE(1:10,1:6),MINSHIFT,MAXSHIFT,MINWAVE,MAXWAVE
   real(real64) DNUMWAVE
   COMMON/TABLESHIFT/SHIFT_TABLE,TABEXIST
   INTEGER NUMWAVE,I,PLV
   COMMON/WAVEMAX/NUMWAVE
   PLV=1
      CALL KDP_EXEC('CHRSHIFT ACC')
   DNUMWAVE=DBLE(NUMWAVE)
   IF(WQ(1:1).EQ.'X') PLV=2
!
!
!     THIS PLOTS CHROMATIC FOCUS SHIFT DATA
   IF(is_command_query()) THEN
      OUTLYNE=&
      &'"PLTCHRSH" PLOTS XZ OR YZ-PLANE CHROMATIC FOCAL SHIFT DATA'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)'RE-ENTER COMMAND'
      CALL SHOWIT(1)
      RETURN
   END IF
   IF(SN.EQ.1.OR.SST.EQ.1) THEN
      OUTLYNE=&
      &'"PLTCHRSH" TAKES NO STRING OR NUMERIC WORD INPUT'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)'RE-ENTER COMMAND'
      CALL SHOWIT(1)
      CALL MACFAL
      RETURN
   END IF
   IF(SQ.EQ.1.AND.WQ.NE.'X') THEN
      OUTLYNE=&
      &'"PLTCHRSH" ONLY TAKES "X" AS OPTIONAL QUALIFIER INPUT'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)'RE-ENTER COMMAND'
      CALL SHOWIT(1)
      CALL MACFAL
      RETURN
   END IF
   IF(.NOT.TABEXIST) THEN
      OUTLYNE=&
      &'A CHROMATIC FOCUS SHIFT TABLE COULD NOT BE GENERATED'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)'NO PLOT WILL BE PRODUCED'
      CALL SHOWIT(1)
      CALL MACFAL
      RETURN
   END IF
   MINWAVE=SHIFT_TABLE(1,2)
   MAXWAVE=SHIFT_TABLE(NUMWAVE,2)
   MINSHIFT=1.0D20
   MAXSHIFT=-1.0D20
   DO I=1,NUMWAVE
      IF(SHIFT_TABLE(I,3).LT.MINSHIFT)MINSHIFT=SHIFT_TABLE(I,3)
      IF(SHIFT_TABLE(I,4).LT.MINSHIFT)MINSHIFT=SHIFT_TABLE(I,4)
      IF(SHIFT_TABLE(I,5).LT.MINSHIFT)MINSHIFT=SHIFT_TABLE(I,5)
      IF(SHIFT_TABLE(I,6).LT.MINSHIFT)MINSHIFT=SHIFT_TABLE(I,6)
      IF(SHIFT_TABLE(I,3).GT.MAXSHIFT)MAXSHIFT=SHIFT_TABLE(I,3)
      IF(SHIFT_TABLE(I,4).GT.MAXSHIFT)MAXSHIFT=SHIFT_TABLE(I,4)
      IF(SHIFT_TABLE(I,5).GT.MAXSHIFT)MAXSHIFT=SHIFT_TABLE(I,5)
      IF(SHIFT_TABLE(I,6).GT.MAXSHIFT)MAXSHIFT=SHIFT_TABLE(I,6)
   END DO
   IF(DABS(MINSHIFT).GT.DABS(MAXSHIFT)) THEN
      MAXSHIFT=DABS(MINSHIFT)
   ELSE
      MINSHIFT=-DABS(MAXSHIFT)
   END IF
   WRITE(AXMIN,20) MINSHIFT
   WRITE(AXMAX,20) MAXSHIFT
   WRITE(AYMIN,20) MINWAVE
   WRITE(AYMAX,20) MAXWAVE
   WRITE(XHIGHH,20) DNUMWAVE
   WRITE(YHIGHH,20) DNUMWAVE+10.0D0
20 FORMAT(G11.4)
      CALL KDP_EXEC('PLOT NEW')
      CALL KDP_EXEC('PLOT UXAXIS '//AXMIN //AXMAX)
      CALL KDP_EXEC('PLOT UYAXIS '//AYMIN //AYMAX)
      CALL KDP_EXEC('PLOT UYLINE 0')
      CALL KDP_EXEC('PLOT UYAXISLB WAVELENGTH IN MICRONS')
   SAVE_KDP(1)=SAVEINPT(1)
   IF(sys_mode().LE.2.0D0) THEN
!     FOCAL
      INPUT='PLOT UXAXISLB FOCAL SHIFT IN MICRONS'
      CALL PROCES
   ELSE
!     AFOCAL
      INPUT='PLOT UXAXISLB FOCAL SHIFT IN MICRO-RADIANS'
      CALL PROCES
   END IF
   REST_KDP(1)=RESTINPT(1)
   IF(PLV.EQ.2) THEN
      SAVE_KDP(1)=SAVEINPT(1)
!
!     REGISTERS USED ARE 1 THROUGH NUMWAVE FOR THE FOCUS SHIFTS
!     AND                11 THROU  10+NUMWAVE FOR THE WAVELENGTHS
!     WE DO THIS FIRST FOR THE XZ-PLANE, THEN THE YZ-PLANE
!
!     XZ-PLAME MARGINAL
      DO I=1,NUMWAVE
         GPREG(I)=SHIFT_TABLE(I,5)
         GPREG(I+10)=SHIFT_TABLE(I,2)
      END DO
      INPUT='PLOT UPLOT 1,'//XHIGHH//',11,'//YHIGHH//',0'
      CALL PROCES
!
      REST_KDP(1)=RESTINPT(1)
      SAVE_KDP(1)=SAVEINPT(1)
!
!     REGISTERS USED ARE 1 THROUGH NUMWAVE FOR THE FOCUS SHIFTS
!     AND                11 THROU  10+NUMWAVE FOR THE WAVELENGTHS
!     WE DO THIS FIRST FOR THE XZ-PLANE, THEN THE YZ-PLANE
!
!     XZ-PLAME CHIEF
      DO I=1,NUMWAVE
         GPREG(I)=SHIFT_TABLE(I,6)
         GPREG(I+10)=SHIFT_TABLE(I,2)
      END DO
      INPUT='PLOT UPLOT 1,'//XHIGHH//',11,'//YHIGHH//',2'
      CALL PROCES
!
      REST_KDP(1)=RESTINPT(1)
   END IF
   IF(PLV.EQ.1) THEN
      SAVE_KDP(1)=SAVEINPT(1)
!
!     REGISTERS USED ARE 1 THROUGH NUMWAVE FOR THE FOCUS SHIFTS
!     AND                11 THROU  10+NUMWAVE FOR THE WAVELENGTHS
!     WE DO THIS FIRST FOR THE XZ-PLANE, THEN THE YZ-PLANE
!
!     YZ-PLAME MARGINAL
      DO I=1,NUMWAVE
         GPREG(I)=SHIFT_TABLE(I,3)
         GPREG(I+10)=SHIFT_TABLE(I,2)
      END DO
      INPUT='PLOT UPLOT 1,'//XHIGHH//',11,'//YHIGHH//',0'
      CALL PROCES
!
      REST_KDP(1)=RESTINPT(1)
      SAVE_KDP(1)=SAVEINPT(1)
!
!     REGISTERS USED ARE 1 THROUGH NUMWAVE FOR THE FOCUS SHIFTS
!     AND                11 THROU  10+NUMWAVE FOR THE WAVELENGTHS
!     WE DO THIS FIRST FOR THE XZ-PLANE, THEN THE YZ-PLANE
!
!     YZ-PLAME CHIEF
      DO I=1,NUMWAVE
         GPREG(I)=SHIFT_TABLE(I,4)
         GPREG(I+10)=SHIFT_TABLE(I,2)
      END DO
      INPUT='PLOT UPLOT 1,'//XHIGHH//',11,'//YHIGHH//',2'
      CALL PROCES
!
      REST_KDP(1)=RESTINPT(1)
   END IF
   SAVE_KDP(1)=SAVEINPT(1)
   INPUT='PLOT CHNOTE 2'
   CALL PROCES
   IF(PLV.EQ.1) THEN
      INPUT='PNOTE FOCAL SHIFT VERSUS WAVELENGTH, YZ-PLANE'
      CALL PROCES
      INPUT='PLOT NOTE 2750 400'
      CALL PROCES
   END IF
   IF(PLV.EQ.2) THEN
      INPUT='PNOTE FOCAL SHIFT VERSUS WAVELENGTH, XZ-PLANE'
      CALL PROCES
      INPUT='PLOT NOTE 2750 400'
      CALL PROCES
   END IF
   INPUT='PLOT LSTYLE 0'
   CALL PROCES
   INPUT='PLOT PEN 2000 6500 3'
   CALL PROCES
   INPUT='PLOT PEN 3000 6500 2'
   CALL PROCES
   INPUT='PLOT LSTYLE 2'
   CALL PROCES
   INPUT='PLOT PEN 2000 6000 3'
   CALL PROCES
   INPUT='PLOT PEN 3000 6000 2'
   CALL PROCES
   INPUT='PLOT CHNOTE 2'
   CALL PROCES
   INPUT='PNOTE MARGINAL RAY AXIAL FOCUS SHIFT'
   CALL PROCES
   INPUT='PLOT NOTE 3200 6500'
   CALL PROCES
   INPUT='PNOTE CHIEF RAY LATERAL SHIFT'
   CALL PROCES
   INPUT='PLOT NOTE 3200 6000'
   CALL PROCES
   INPUT='PLOT LSTYLE 2'
   CALL PROCES
   INPUT='PLOT CHNOTE 1'
   CALL PROCES
   REST_KDP(1)=RESTINPT(1)
      CALL KDP_EXEC('DRAW')
!
!
   RETURN
END
! SUB CHRSHIFT.FOR
SUBROUTINE CHRSHIFT
   use DATLEN
   use DATMAI
   use command_utils, only: is_command_query
   use mod_system, only: sys_mode, sys_units, sys_wavelength, sys_wl_ref, sys_wl_weight
   use iso_fortran_env, only: real64
   IMPLICIT NONE
   LOGICAL AF,TABEXIST
   INTEGER WVCOUNT,I,J,K
   INTEGER NUMWAVE
   COMMON/WAVEMAX/NUMWAVE
   real(real64) SHIFT_TABLE(1:10,1:6),LAM_TABLE(1:10,1:2)
   real(real64) JK_A(1:10),JK_1(1:10),JK_2(1:10),ZERO(1:4)
   real(real64) SPY,SPUY,SPCY,SPUCY
   real(real64) SPX,SPUX,SPCX,SPUCX
   real(real64) SCWPY,SCWPUY,SCWPCY,SCWPUCY
   real(real64) SCWPX,SCWPUX,SCWPCX,SCWPUCX
   COMMON/TABLESHIFT/SHIFT_TABLE,TABEXIST
   CHARACTER LAM_CHAR(1:10)*2,CW_CHAR*2
   LOGICAL NOPRINT
   NOPRINT=.FALSE.
   IF(WQ.EQ.'ACC') THEN
      NOPRINT=.TRUE.
      SQ=0
      WQ='        '
   END IF

   IF(is_command_query()) THEN
      OUTLYNE=&
      &'"CHRSHIFT" DISPLAYS CHROMATIC FOCUS SHIFT DATA'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)'RE-ENTER COMMAND'
      CALL SHOWIT(1)
      RETURN
   END IF
   IF(SQ.EQ.1.OR.SN.EQ.1.OR.SST.EQ.1) THEN
      OUTLYNE=&
      &'"CHRSHIFT" TAKES NO ADDITIONAL INPUT'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)'RE-ENTER COMMAND'
      CALL SHOWIT(1)
      CALL MACFAL
      RETURN
   END IF
!     AFOCAL OR NOT
   AF=.FALSE.
   IF(sys_mode().GE.3.0D0) AF=.TRUE.
!     ENOUGH WAVELENGTHS ?
   WVCOUNT=0
   TABEXIST=.FALSE.
   IF(sys_wavelength(1).NE.0.0D0.AND.sys_wl_weight(1).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(2).NE.0.0D0.AND.sys_wl_weight(2).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(3).NE.0.0D0.AND.sys_wl_weight(3).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(4).NE.0.0D0.AND.sys_wl_weight(4).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(5).NE.0.0D0.AND.sys_wl_weight(5).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(6).NE.0.0D0.AND.sys_wl_weight(6).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(7).NE.0.0D0.AND.sys_wl_weight(7).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(8).NE.0.0D0.AND.sys_wl_weight(8).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(9).NE.0.0D0.AND.sys_wl_weight(9).NE.0.0D0) WVCOUNT=WVCOUNT+1
   IF(sys_wavelength(10).NE.0.0D0.AND.sys_wl_weight(10).NE.0.0D0) WVCOUNT=WVCOUNT+1
!
   IF(WVCOUNT.LE.1) THEN
      WRITE(OUTLYNE,*)&
      &'MORE THAN ONE ACTIVE WAVELENGTH MUST EXIST FOR "CRSHIFT"'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)&
      &'TO WORK.'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)'NO ACTION TAKEN'
      CALL SHOWIT(1)
      CALL MACFAL
      RETURN
   END IF
   LAM_TABLE(1:10,1:2)=0.0D0
   SHIFT_TABLE(1:10,1:6)=0.0D0
!     SORT ACTIVE WAVELENGTS AND COUNT MAXIMUM ACTIVE WAVELENGTHS
   J=0
   IF(sys_wavelength(1).NE.0.0D0.AND.sys_wl_weight(1).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=1.0D0
      LAM_TABLE(J,2)=sys_wavelength(1)
   END IF
   IF(sys_wavelength(2).NE.0.0D0.AND.sys_wl_weight(2).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=2.0D0
      LAM_TABLE(J,2)=sys_wavelength(2)
   END IF
   IF(sys_wavelength(3).NE.0.0D0.AND.sys_wl_weight(3).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=3.0D0
      LAM_TABLE(J,2)=sys_wavelength(3)
   END IF
   IF(sys_wavelength(4).NE.0.0D0.AND.sys_wl_weight(4).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=4.0D0
      LAM_TABLE(J,2)=sys_wavelength(4)
   END IF
   IF(sys_wavelength(5).NE.0.0D0.AND.sys_wl_weight(5).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=5.0D0
      LAM_TABLE(J,2)=sys_wavelength(5)
   END IF
   IF(sys_wavelength(6).NE.0.0D0.AND.sys_wl_weight(6).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=6.0D0
      LAM_TABLE(J,2)=sys_wavelength(6)
   END IF
   IF(sys_wavelength(7).NE.0.0D0.AND.sys_wl_weight(7).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=7.0D0
      LAM_TABLE(J,2)=sys_wavelength(7)
   END IF
   IF(sys_wavelength(8).NE.0.0D0.AND.sys_wl_weight(8).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=8.0D0
      LAM_TABLE(J,2)=sys_wavelength(8)
   END IF
   IF(sys_wavelength(9).NE.0.0D0.AND.sys_wl_weight(9).NE.0.0D0) THEN
      LAM_TABLE(J,1)=9.0D0
      LAM_TABLE(J,2)=sys_wavelength(9)
   END IF
   IF(sys_wavelength(10).NE.0.0D0.AND.sys_wl_weight(10).NE.0.0D0) THEN
      J=J+1
      LAM_TABLE(J,1)=10.0D0
      LAM_TABLE(J,2)=sys_wavelength(10)
   END IF
   NUMWAVE=J
!     WE NOW HAVE NUMWAVE ENTRIES IN LAM_TABLE TO SORT BY
!     INCREASING WAVELENGTH IN MICRONS
   DO I=1,NUMWAVE
      JK_A(I)=LAM_TABLE(I,2)
      JK_1(I)=LAM_TABLE(I,1)
      JK_2(I)=LAM_TABLE(I,2)
   END DO
   CALL SORT_JK1(NUMWAVE,JK_A(1:NUMWAVE),JK_1(1:NUMWAVE)&
   &,JK_2(1:NUMWAVE))
   DO I=1,NUMWAVE
      LAM_TABLE(I,1)=JK_1(I)
      LAM_TABLE(I,2)=JK_2(I)
      SHIFT_TABLE(I,1)=JK_1(I)
      SHIFT_TABLE(I,2)=JK_2(I)
   END DO
   DO I=1,NUMWAVE
      IF(SHIFT_TABLE(I,1).EQ.1.0D0)  LAM_CHAR(I)=' 1'
      IF(SHIFT_TABLE(I,1).EQ.2.0D0)  LAM_CHAR(I)=' 2'
      IF(SHIFT_TABLE(I,1).EQ.3.0D0)  LAM_CHAR(I)=' 3'
      IF(SHIFT_TABLE(I,1).EQ.4.0D0)  LAM_CHAR(I)=' 4'
      IF(SHIFT_TABLE(I,1).EQ.5.0D0)  LAM_CHAR(I)=' 5'
      IF(SHIFT_TABLE(I,1).EQ.6.0D0)  LAM_CHAR(I)=' 6'
      IF(SHIFT_TABLE(I,1).EQ.7.0D0)  LAM_CHAR(I)=' 7'
      IF(SHIFT_TABLE(I,1).EQ.8.0D0)  LAM_CHAR(I)=' 8'
      IF(SHIFT_TABLE(I,1).EQ.9.0D0)  LAM_CHAR(I)=' 9'
      IF(SHIFT_TABLE(I,1).EQ.10.0D0) LAM_CHAR(I)='10'
   END DO
   DO I=1,NUMWAVE
      IF(sys_wl_ref().EQ.1.0D0)   CW_CHAR=' 1'
      IF(sys_wl_ref().EQ.2.0D0)   CW_CHAR=' 2'
      IF(sys_wl_ref().EQ.3.0D0)   CW_CHAR=' 3'
      IF(sys_wl_ref().EQ.4.0D0)   CW_CHAR=' 4'
      IF(sys_wl_ref().EQ.5.0D0)   CW_CHAR=' 5'
      IF(sys_wl_ref().EQ.6.0D0)   CW_CHAR=' 6'
      IF(sys_wl_ref().EQ.7.0D0)   CW_CHAR=' 7'
      IF(sys_wl_ref().EQ.8.0D0)   CW_CHAR=' 8'
      IF(sys_wl_ref().EQ.9.0D0)   CW_CHAR=' 9'
      IF(sys_wl_ref().EQ.10.0D0)  CW_CHAR='10'
   END DO
   SAVE_KDP(13)=SAVEINPT(13)
   INPUT='GET PY,,'//CW_CHAR
   CALL PROCES
   SCWPY=REG(9)
   REST_KDP(13)=RESTINPT(13)
   SAVE_KDP(13)=SAVEINPT(13)
   INPUT='GET PUY,,'//CW_CHAR
   CALL PROCES
   SCWPUY=REG(9)
   REST_KDP(13)=RESTINPT(13)
   SAVE_KDP(13)=SAVEINPT(13)
   INPUT='GET PCY,,'//CW_CHAR
   CALL PROCES
   SCWPCY=REG(9)
   REST_KDP(13)=RESTINPT(13)
   SAVE_KDP(13)=SAVEINPT(13)
   INPUT='GET PUCY,,'//CW_CHAR
   CALL PROCES
   SCWPUCY=REG(9)
   REST_KDP(13)=RESTINPT(13)
   SAVE_KDP(13)=SAVEINPT(13)
   INPUT='GET PX,,'//CW_CHAR
   CALL PROCES
   SCWPX=REG(9)
   REST_KDP(13)=RESTINPT(13)
   SAVE_KDP(13)=SAVEINPT(13)
   INPUT='GET PUX,,'//CW_CHAR
   CALL PROCES
   SCWPUX=REG(9)
   REST_KDP(13)=RESTINPT(13)
   SAVE_KDP(13)=SAVEINPT(13)
   INPUT='GET PCX,,'//CW_CHAR
   CALL PROCES
   SCWPCX=REG(9)
   REST_KDP(13)=RESTINPT(13)
   SAVE_KDP(13)=SAVEINPT(13)
   INPUT='GET PUCX,,'//CW_CHAR
   CALL PROCES
   SCWPUCX=REG(9)
   REST_KDP(13)=RESTINPT(13)
!
   IF(.NOT.AF) THEN
!     FOCAL
      ZERO(1)=-SCWPY*SCWPUY
      ZERO(2)=SCWPCY
      ZERO(3)=-SCWPX*SCWPUX
      ZERO(4)=SCWPCX
   ELSE
!     AFOCAL
      ZERO(1)=SCWPUY
      ZERO(2)=SCWPUCY
      ZERO(3)=SCWPUX
      ZERO(4)=SCWPUCX
   END IF
!
   IF(.NOT.NOPRINT) THEN
      IF(.NOT.AF) WRITE(OUTLYNE,20)
      IF(AF) WRITE(OUTLYNE,21)
      CALL SHOWIT(0)
      WRITE(OUTLYNE,24)
      CALL SHOWIT(0)
      WRITE(OUTLYNE,23)
      CALL SHOWIT(0)
20    FORMAT('CHROMATIC SHIFT IN MICRONS, WAVELENGTH IN MICRONS')
21    FORMAT('CHROMATIC SHIFT IN MILLIRADIANS, WAVELENGTH IN MICRONS')
24    FORMAT('ALL SHIFTS REFERENCED TO THE CURRENT CONTROL WAVELENGTH')
22    FORMAT('WAVELENGTH',3X,'MARG. Y-SHIFT',3X,'CHIEF Y-SHIFT'&
      &,3X,'MARG. X-SHIFT',3X,'CHIEF X-SHIFT')
      WRITE(OUTLYNE,22)
      CALL SHOWIT(0)
29    FORMAT(' (MICRONS)',2X,'(AXIAL MOTION)',3X,'(TRANSVERSE) '&
      &,2X,'(AXIAL MOTION)',3X,'(TRANSVERSE) ')
      WRITE(OUTLYNE,29)
      CALL SHOWIT(0)
23    FORMAT(1X)
   END IF

   DO I=1,NUMWAVE
      SAVE_KDP(13)=SAVEINPT(13)
      INPUT='GET PY,,'//LAM_CHAR(I)
      CALL PROCES
      SPY=REG(9)
      REST_KDP(13)=RESTINPT(13)
      SAVE_KDP(13)=SAVEINPT(13)
      INPUT='GET PUY,,'//LAM_CHAR(I)
      CALL PROCES
      SPUY=REG(9)
      REST_KDP(13)=RESTINPT(13)
      SAVE_KDP(13)=SAVEINPT(13)
      INPUT='GET PCY,,'//LAM_CHAR(I)
      CALL PROCES
      SPCY=REG(9)
      REST_KDP(13)=RESTINPT(13)
      SAVE_KDP(13)=SAVEINPT(13)
      INPUT='GET PUCY,,'//LAM_CHAR(I)
      CALL PROCES
      SPUCY=REG(9)
      REST_KDP(13)=RESTINPT(13)
      SAVE_KDP(13)=SAVEINPT(13)
      INPUT='GET PX,,'//LAM_CHAR(I)
      CALL PROCES
      SPX=REG(9)
      REST_KDP(13)=RESTINPT(13)
      SAVE_KDP(13)=SAVEINPT(13)
      INPUT='GET PUX,,'//LAM_CHAR(I)
      CALL PROCES
      SPUX=REG(9)
      REST_KDP(13)=RESTINPT(13)
      SAVE_KDP(13)=SAVEINPT(13)
      INPUT='GET PCX,,'//LAM_CHAR(I)
      CALL PROCES
      SPCX=REG(9)
      REST_KDP(13)=RESTINPT(13)
      SAVE_KDP(13)=SAVEINPT(13)
      INPUT='GET PUCX,,'//LAM_CHAR(I)
      CALL PROCES
      SPUCX=REG(9)
      REST_KDP(13)=RESTINPT(13)

      IF(.NOT.AF) THEN
!     FOCAL
!     CONVERT TO MICRONS
         SHIFT_TABLE(I,3)=(-SPY*SPUY)-ZERO(1)
         SHIFT_TABLE(I,4)=(SPCY)-ZERO(2)
         SHIFT_TABLE(I,5)=(-SPX*SPUX)-ZERO(3)
         SHIFT_TABLE(I,6)=(SPCX)-ZERO(4)
         DO K=3,6
            IF(sys_units().EQ.1.0D0)&
            &SHIFT_TABLE(I,K)=(SHIFT_TABLE(I,K)/25.4D0)*1.0D3
            IF(sys_units().EQ.2.0D0)&
            &SHIFT_TABLE(I,K)=SHIFT_TABLE(I,K)*1.0D4
            IF(sys_units().EQ.3.0D0)&
            &SHIFT_TABLE(I,K)=SHIFT_TABLE(I,K)*1.0D3
            IF(sys_units().EQ.4.0D0)&
            &SHIFT_TABLE(I,K)=SHIFT_TABLE(I,K)*1.0D6
         END DO
      ELSE
!     AFOCAL
!     CONVERT TO MILLIRADIANS
         SHIFT_TABLE(I,3)=DATAN(SPUY-ZERO(1))*1.0D3
         SHIFT_TABLE(I,4)=DATAN(SPUCY-ZERO(2))*1.0D3
         SHIFT_TABLE(I,5)=DATAN(SPUX-ZERO(3))*1.0D3
         SHIFT_TABLE(I,6)=DATAN(SPUCX-ZERO(4))*1.0D3
      END IF
      IF(.NOT.NOPRINT) THEN
         WRITE(OUTLYNE,10) SNGL(SHIFT_TABLE(I,2)),SHIFT_TABLE(I,3)&
         &,SHIFT_TABLE(I,4),SHIFT_TABLE(I,5)&
         &,SHIFT_TABLE(I,6)
         CALL SHOWIT(0)
      END IF
   END DO
   REST_KDP(1)=RESTINPT(1)

   TABEXIST=.TRUE.
10 FORMAT(F10.5,3X,G13.6,3X,G13.6,3X,G13.6,3X,G13.6)
   CHRSHIFTEXT=.TRUE.
   RETURN
END
! SUB PLTAX.FOR
SUBROUTINE PLTAX
!
   use DATLEN
   use DATMAI
   use command_utils, only: is_command_query
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
!       THIS ROUTINE DOES PLOT AXIS AND PLOT NOAXIS AT THE CMD LEVEL
!
!
!       PLOT AXIS
!
   IF(WC.EQ.'PLOT'.AND.WQ.EQ.'AXIS') THEN
!       CHECK SYNTAX
      IF(SST.EQ.1.OR.SN.EQ.1) THEN
         CALL REPORT_ERROR_AND_FAIL(&
         & '"PLOT AXIS" TAKES NO NUMERIC OR STRING INPUT'//'\n'//&
         & 'RE-ENTER COMMAND', 1)
         RETURN
      END IF
      PLTAXS=.TRUE.
      CALL DOAX
      IF(is_command_query()) THEN
         IF(PLTAXS) OUTLYNE= 'AXIS PLOTTING IS CURRENTLY ENABLED'
         IF(.NOT.PLTAXS)&
         &OUTLYNE= 'AXIS PLOTTING IS NOT CURRENTLY ENABLED'
         CALL SHOWIT(1)
         RETURN
      END IF
      RETURN
   END IF
   RETURN
END
! SUB PLTACC.FOR
SUBROUTINE PLTACC
!
   use DATHGR
   use DATLEN
   use DATMAI
   use command_utils, only: is_command_query
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
!       THIS ROUTINE DOES THE "PLOT ACC" COMMAND AT THE CMD LEVEL
!       THE SIZE AND ANGLE ARE RESET USING "PLOT CHNOTE"
!
   INTEGER COLPAS,DECIM,IIX,IIY,I,IB
!
   LOGICAL INTEG
!
   CHARACTER CNUMBR*40
!
!
!       CHECK SYNTAX
   IF(S5.EQ.1) THEN
      CALL REPORT_ERROR_AND_FAIL(&
      & '"PLOT ACC" TAKES NO NUMERIC WORD #5 INPUT'//'\n'//&
      & 'RE-ENTER COMMAND', 1)
      RETURN
   ELSE
   END IF
   IF(W3.LT.0.0D0.OR.W3.GT.10.0D0) THEN
      OUTLYNE=&
      &'VALID NUMERIC WORD #3 VALUES ARE: 1,2,3,4,5,6,7,8,9 OR 10'
      CALL SHOWIT(1)
      CALL REPORT_ERROR_AND_FAIL('RE-ENTER COMMAND', 1)
      RETURN
   ELSE
   END IF
   IF(SST.EQ.1) THEN
      CALL REPORT_ERROR_AND_FAIL('"PLOT ACC" TAKES NO STRING INPUT'//'\n'//'RE-ENTER COMMAND', 1)
      RETURN
   ELSE
   END IF
!       STI
   IF(is_command_query()) THEN
!
      WRITE(OUTLYNE,15) REG(9)
      CALL SHOWIT(0)
15    FORMAT('THE ACCUMULATOR VALUE TO BE PLOTTED IS = ',D23.15)
      RETURN
   ELSE
!       NOT ?, DO THE PLOTTING
   END IF
!       DEFAULT VALUE DETERMINATIONS
!       IF W1 IS DEFAULT, USE THE CURRENT CURRENT X PEN POS
   IF(DF1.EQ.1) W1=DBLE(PENPOSX)
!       IF W2 IS DEFAULT, USE THE CURRENT CURRENT Y PEN POS
   IF(DF2.EQ.1) W2=DBLE(PENPOSY)
!       IF W3 IS DEFAULT, W3=3.0D0
   IF(DF3.EQ.1) W3=3.0D0
!       IF W4 IS DEFAULT, SET INTEG FALSE
   IF(DF4.EQ.1) INTEG=.FALSE.
!
   DECIM=INT(W3)
   IF(W4.NE.0.0D0) INTEG=.TRUE.
   IF(W4.EQ.0.0D0) INTEG=.FALSE.
   CALL HMAT(REG(9),DECIM,CNUMBR,INTEG,IB)
!
!       HERE IS WHERE THE ACCUMULATOR CONTENTS ARE PLOTTED
!
   COLPAS=COLLBL
   CALL MY_COLTYP(COLPAS)
   IIX=INT(W1)
   IIY=INT(W2)
   IF(.NOT.PLEXIS) PLEXIS=.TRUE.
   CALL MY_JUSTSTRING(IIX,IIY,CNUMBR(1:IB),NTANG,NTSIZ,3,3)

!
   RETURN
END
! SUB PLTABL.FOR
SUBROUTINE PLTABL
!
   use DATHGR
   use DATLEN
   use DATMAI
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
!       THIS SUBROUTINE IS CALLED TO ENTER THE SPECT LEVEL
!       COMMAND "PLOT" AT THE SPECTR LEVEL
!
   CHARACTER TNAME*8,LABX*40,LABY*40,ANUMBER*40
!
   INTEGER CTAB,I,NT1SIZ,NT1ANG,FEND,COLPAS,IX(1:1001),IY(1:1001)
   INTEGER NX,NY
!
   REAL NUMJIM,NUMBER,OXMIN,OXMAX,OYMIN,OYMAX,DELF1,DELX1
!
   LOGICAL TORR
!
   COMMON/TTOORR/TORR
!
   REAL X(1:1001),Y(1:1001),LLIM,ULIM,UFUNC,LFUNC,RDELA,RDELB &
   &,HOLD,RDELC
!
   real(real64) LAMB1,LAMB2,TABLE(1:1001,1:3)
!
   COMMON/TABL/TABLE,CTAB
!
   COMMON/CURNAM/TNAME
!
!
   LABX='WAVELENGTH (MICRONS)                    '
   NX=20
   IF(TORR)      LABY='TRANSMITTANCE                           '
   IF(TORR)      NY=13
   IF(.NOT.TORR) LABY='REFLECTANCE                             '
   IF(.NOT.TORR) NY=11
!
!     GENERATE GRAPHIC
!     DO A PLOT NEW
   DEVTYP=1
   LOOKY=0.0D0
   LOOKX=-1.0D0
   LOOKZ=0.0D0
   CALL PLTDEV
   GRASET=.TRUE.
   PLEXIS=.TRUE.
!     SET LETTER SIZE AND ANGLE
   NT1SIZ=1
   NT1ANG=0
   CALL MY_SETCHARASPECT(1.5,1.5)
!       LOWER AND UPPER LIMITS OF WAVELENGTH ARE
   LAMB1=TABLE(1,2)
   LAMB2=TABLE(CTAB,2)
!       CTAB IS THE MAXIMUM NUMBER OF ENTRIES IN THE TABLE ARRAYS
!       PROCEED
!
   DO 10 I = 1, CTAB
      X(I)  = REAL(TABLE(I,2))
      Y(I)  = REAL(TABLE(I,3))
10 CONTINUE
!
!       NOW DETERMINE THE LOWER AND UPPER X LIMITS OF THE PLOT
!
!       LAMB1 IS THE SHORTEST WAVELENGTH, LLIM WILL BE THE NEXT
!       LOWEST INTEGER VALUE OF WAVELENGTH IN MICRONS
   LLIM=REAL(LAMB1)
   IF(LLIM.LT.0) LLIM=0
!       AND THE UPPER LIMIT IS CONVERSELY:
   ULIM=REAL(LAMB2)
!       MAX FUNCTIONAL VALUE IS:
   UFUNC=TABLE(1,3)
   DO I=2,CTAB
      IF(TABLE(I,3).GE.UFUNC) UFUNC=TABLE(I,3)
   END DO
!       MIN FUNCTIONAL VALUE IS:
   LFUNC=TABLE(1,3)
   DO I=2,CTAB
      IF(TABLE(I,3).LE.LFUNC) LFUNC=TABLE(I,3)
   END DO
!       DEFAULT OVERRIDES DONE HERE
!
   IF(DF2.EQ.0) LLIM=REAL(W2)
   IF(DF3.EQ.0) ULIM=REAL(W3)
   IF(DF4.EQ.0) LFUNC=REAL(W4)
   IF(DF5.EQ.0) UFUNC=REAL(W5)
   IF(LLIM.GE.ULIM) THEN
!
      HOLD=ULIM
      ULIM=LLIM
      LLIM=HOLD
   ELSE
   END IF
!
   IF(LFUNC.GE.UFUNC) THEN
      HOLD=UFUNC
      UFUNC=LFUNC
      LFUNC=HOLD
   ELSE
   END IF
   IF(LLIM.EQ.ULIM) THEN
      RETURN
   END IF
!
!
!       CORRECT SCALING IS IMPORTANT
   DO I=1,CTAB
      IX(I)=INT((((X(I)-LLIM)/(ULIM-LLIM))*6000.0)+2000.0)
      IY(I)=INT((((Y(I)-LFUNC)/(UFUNC-LFUNC))*4200.0)+1400.0)
   END DO
!
   DELF1=(UFUNC-LFUNC)/10.0
   DELX1=(ULIM-LLIM)/5.0
   IF(ULIM.EQ.LLIM) THEN
      CALL REPORT_ERROR_AND_FAIL(&
      & 'UPPER AND LOWER WAVELENGTH VALUES ARE EQUAL'//'\n'//&
      & 'NO PLOT CAN BE GENERATED'//'\n'//&
      & 'RE-ENTER COMMAND', 1)
      RETURN
   END IF

!     SET LETTER SIZE AND ANGLE
   NT1SIZ=1
   NT1ANG=0
   CALL MY_SETCHARASPECT(1.5,1.5)
!     LIFT PEN, MOVE TO FRAME START
!     PLOT THE BIG BOX
   CALL PLOTBOX
!       LOWER AND UPPER LIMITS OF WAVELENGTH ARE
   LAMB1=TABLE(1,2)
   LAMB2=TABLE(CTAB,2)
!       CTAB IS THE MAXIMUM NUMBER OF ENTRIES IN THE TABLE ARRAYS
!       PROCEED
!
!     PLOT THE AXES AND TICS
   CALL PLOTAXES3
!     PLOT THE HORIZONTAL AXIS NAME
   CALL PLOTHNAME(LABX,NX)
!     PLOT THE VERTICAL AXIS NAME
   CALL PLOTVNAME(LABY,NY)

!     PLOT THE VALUES FOR THE TIC MARKS
   CALL PLOTVVAL(LFUNC,DELF1)
   CALL PLOTHVAL(LLIM,DELX1)

!
   RDELA=ULIM-LLIM
   RDELC=UFUNC-LFUNC
   IF(RDELC.EQ.0.0) RDELB=0.1
   IF(RDELC.NE.0.0) RDELB=RDELC/10.0
!
   COLPAS=COLSPE
   CALL MY_COLTYP(COLPAS)
   FEND=CTAB
   CALL PLOTFUNC2(X,Y,FEND,LLIM,ULIM,LFUNC,UFUNC,150)
   IF(.NOT.PLEXIS) PLEXIS=.TRUE.
      CALL KDP_EXEC('DRAW')
   RETURN
END
!     THE FOLLOWING ARE FOR LSF AND FIELD ABERRATION PLOTS
SUBROUTINE PLOTFUNC2(X,Y,FEND,LLIM,ULIM,LFUNC,UFUNC,SPNUM)
!
   use DATHGR
   use DATLEN
   use DATMAI
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
   REAL X,Y,LLIM,ULIM,LFUNC,UFUNC
!
   real(real64) Y2,XX,YY,XDEL,XXX,YYY
!
   INTEGER FEND,I,IX,IY,ALLOERR,SPNUM,COLPAS
!
   DIMENSION IX(:),IY(:),X(FEND),Y(FEND),XX(:),YY(:)
   ALLOCATABLE :: IX,IY,XX,YY
!
   DEALLOCATE(IX,IY,XX,YY,STAT=ALLOERR)

   ALLOCATE(IX(1:FEND),IY(1:SPNUM)&
   &,XX(1:FEND),YY(1:FEND),STAT=ALLOERR)
   COLPAS=COLDEF
   CALL MY_COLTYP(COLPAS)
   DO I=1,FEND
      XX(I)=DBLE(X(I))
      YY(I)=DBLE(Y(I))
   END DO
   DO I=1,FEND
      IX(I)=INT((((REAL(XX(I))-LLIM)/(ULIM-LLIM))*6000.0)+2000.0)
      IY(I)=INT((((REAL(YY(I))-LFUNC)/(UFUNC-LFUNC))*4200.0)+1400.0)
   END DO

   CALL MY_PLOTC(IX(1),IY(1),0,0,2000,8000,1400,5600)
   DO I=1,FEND
      CALL MY_PLOTC(IX(I),IY(I),1,0,2000,8000,1400,5600)
   END DO
   DEALLOCATE(IX,IY,XX,YY,STAT=ALLOERR)
END
!     THE FOLLOWING ARE FOR LSF AND FIELD ABERRATION PLOTS
SUBROUTINE PLOTFUNC3(X,Y,FEND,LLIM,ULIM,LFUNC,UFUNC,SPNUM)
!
   use DATHGR
   use DATLEN
   use DATMAI
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
   REAL X,Y,LLIM,ULIM,LFUNC,UFUNC
!
   real(real64) Y2,XX,YY,XDEL,XXX,YYY
!
   INTEGER FEND,I,IX,IY,ALLOERR,SPNUM,COLPAS
!
   DIMENSION IX(:),IY(:),X(FEND),Y(FEND),XX(:),YY(:),&
   &Y2(:),XXX(:),YYY(:)
   ALLOCATABLE :: IX,IY,XX,YY,Y2,XXX,YYY
!
   DEALLOCATE(IX,IY,XX,YY,Y2,XXX,YYY,STAT=ALLOERR)

   ALLOCATE(IX(1:SPNUM),IY(1:SPNUM),Y2(1:FEND)&
   &,XX(1:SPNUM),YY(1:SPNUM),XXX(1:SPNUM),YYY(1:SPNUM)&
   &,STAT=ALLOERR)
   COLPAS=COLDEF
   CALL MY_COLTYP(COLPAS)
   DO I=1,FEND
      XXX(I)=DBLE(X(I))
      YYY(I)=DBLE(Y(I))
   END DO
   CALL SPLINE(XXX,YYY,FEND,1.0D31,1.0D31,Y2)
   XX(1)=DBLE(LLIM)
   CALL SPLINT(XXX,YYY,Y2,FEND,XX(1),YY(1))
   XDEL=DBLE(ULIM-LLIM)/(DBLE(SPNUM-1))
   DO I=2,SPNUM
      XX(I)=XX(I-1)+XDEL
      CALL SPLINT(XXX,YYY,Y2,FEND,XX(I),YY(I))
   END DO
   DO I=1,SPNUM
      IX(I)=INT((((REAL(XX(I))-LLIM)/(ULIM-LLIM))*4000.0)+3000.0)
      IY(I)=INT((((REAL(YY(I))-LFUNC)/(UFUNC-LFUNC))*3500.0)+1500.0)
   END DO

   CALL MY_PLOTC(IX(1),IY(1),0,0,3000,7000,1500,5000)
   DO I=2,SPNUM
      CALL MY_PLOTC(IX(I),IY(I),1,0,3000,7000,1500,5000)
   END DO

   DEALLOCATE(IX,IY,XX,YY,Y2,XXX,YYY,STAT=ALLOERR)
END

