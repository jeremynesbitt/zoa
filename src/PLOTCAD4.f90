SUBROUTINE PLOTUFUNC
!
   use DATHGR
   use DATSUB
   use DATLEN
   use DATMAI
   use command_utils, only: is_command_query
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
   INTEGER IX,IY,I,J,ALLOERR,LXREG,MXREG,LYREG,MYREG
!
   LOGICAL USCALEX,USCALEY
   COMMON/SCALEU/USCALEX,USCALEY
   INTEGER COLPAS
   REAL YL,YU,SCALEITX,SCALEITY
   COMMON/YLYU/YL,YU
   REAL XL,XU
   COMMON/XLXU/XL,XU
!
   IF(is_command_query()) THEN
      OUTLYNE='"PLOT UPLOT" PLOTS THE USER-DEFINED FUNCTION'
      CALL SHOWIT(1)
      RETURN
   END IF
   IF(SST.EQ.1) THEN
      CALL REPORT_ERROR_AND_FAIL('"PLOT UPLOT" TAKES NO STRING INPUT'//'\n'//'RE-ENTER COMMAND', 1)
      RETURN
   END IF
   IF(S5.EQ.1) LNTYPE=0
   IF(F5.EQ.0) LNTYPE=INT(W5)
   IF(LNTYPE.LT.0.OR.LNTYPE.GT.9) LNTYPE=0
   IF(DF1.EQ.1.OR.DF2.EQ.1.OR.DF3.EQ.1.OR.DF4.EQ.1) THEN
      CALL REPORT_ERROR_AND_FAIL(&
      & '"PLOT UPLOT" REQUIRES EXPLICIT'//'\n'//&
      & '"NUMERIC WORD #1 TO #4 INPUT'//'\n'//&
      & 'RE-ENTER COMMAND', 1)
      RETURN
   END IF
   IF(W2.LE.W1) THEN
      CALL REPORT_ERROR_AND_FAIL(&
      & '"PLOT UPLOT" REQUIRES NUMERIC WORD #2 TO BE GREATER'//'\n'//&
      & '"THAN NUMERIC WORD #1'//'\n'//&
      & 'RE-ENTER COMMAND', 1)
      RETURN
   END IF
   IF(W4.LE.W3) THEN
      CALL REPORT_ERROR_AND_FAIL(&
      & '"PLOT UPLOT" REQUIRES NUMERIC WORD #4 TO BE GREATER'//'\n'//&
      & '"THAN NUMERIC WORD #3'//'\n'//&
      & 'RE-ENTER COMMAND', 1)
      RETURN
   END IF
   IF(.NOT.USCALEX) THEN
      CALL REPORT_ERROR_AND_FAIL(&
      & '"PLOT UPLOT" REQUIRES THE X-AXIS TO BE PLOTTED FIRST'//'\n'//&
      & 'RE-ENTER COMMAND', 1)
      RETURN
   END IF
   IF(.NOT.USCALEY) THEN
      CALL REPORT_ERROR_AND_FAIL(&
      & '"PLOT UPLOT" REQUIRES THE Y-AXIS TO BE PLOTTED FIRST'//'\n'//&
      & 'RE-ENTER COMMAND', 1)
      RETURN
   END IF
   LXREG=INT(W1)
   MXREG=INT(W2)
   LYREG=INT(W3)
   MYREG=INT(W4)
   IF(W1.LT.1.0D0.OR.W1.GT.MAXREG.OR.&
   &W2.LT.1.0D0.OR.W2.GT.MAXREG.OR.&
   &W3.LT.1.0D0.OR.W3.GT.MAXREG.OR.&
   &W4.LT.1.0D0.OR.W4.GT.MAXREG) THEN
      OUTLYNE='GENERAL PURPOSE STORAGE REGISTER NUMBER OUT OF RANGE'
      CALL SHOWIT(1)
      WRITE(OUTLYNE,*)&
      &'VALID VALUES FROM 1 TO ',MAXREG,' FOR EACH ENTRY'
      CALL SHOWIT(1)
      CALL REPORT_ERROR_AND_FAIL('RE-ENTER COMMAND', 1)
      RETURN
   END IF
   COLPAS=COLPEN
   CALL MY_COLTYP(COLPAS)

   SCALEITX=(UIXSTOP-UIXSTART)/(XU-XL)
   SCALEITY=(UIYSTOP-UIYSTART)/(YU-YL)

   I=LXREG-1
   J=LYREG-1
   IX=INT(((GPREG(I+1)-XL)*SCALEITX)+UIXSTART)
   IY=INT(((GPREG(J+1)-YL)*SCALEITY)+UIYSTART)
   CALL MY_PLOTC(IX,IY,0,0,UIXSTART,UIXSTOP,UIYSTART,UIYSTOP)
100 CONTINUE
   I=I+1
   J=J+1
   IX=INT(((GPREG(I)-XL)*SCALEITX)+UIXSTART)
   IY=INT(((GPREG(J)-YL)*SCALEITY)+UIYSTART)
   CALL MY_PLOTC(IX,IY,1,LNTYPE,UIXSTART,UIXSTOP,UIYSTART,UIYSTOP)
   IF(I.GE.MXREG.OR.J.GE.MYREG) THEN
      RETURN
   ELSE
      GO TO 100
   END IF
END
