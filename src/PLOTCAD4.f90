   DO I=2,SPNUM
      CALL MY_PLOTC(IX(I),IY(I),1,LT,2000,7000,1400,5600)
   END DO
   DEALLOCATE(IX,IY,XX,YY,Y2,XXX,YYY,STAT=ALLOERR)
END
