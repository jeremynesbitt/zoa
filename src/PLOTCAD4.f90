         IF(W4.NE.0.0D0) THEN
            IF(I.NE.1.AND.I.NE.INT(UUDY)+1) GO TO 5
         END IF
         CALL HMAT(DBLE(NUMBER),3,ANUMBER,.FALSE.,IB)
         CALL MY_JUSTSTRING(UIXSTART-1000,UIYSTART+IY-50,&
         &ANUMBER(1:IB),0,1,3,3)
5        CONTINUE
         NUMJIM=NUMJIM+DELF1
         NUMBER=NUMJIM
         IY=IY+DIY
      END DO
   END IF
   GRASET=.TRUE.
   PLEXIS=.TRUE.
   USCALEX=.TRUE.
   RETURN
END
