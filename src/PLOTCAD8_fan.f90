!       SPLIT FROM PLOTCAD8.FOR FOR SMALLER IFX COMPILATION UNITS

SUBROUTINE FANTP
   use plot_geometry
!
   use DATHGR
   use DATLEN
   use DATMAI
   use mod_system, only: sys_mode, sys_units
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
!       THIS ROUTINE DOES THE PLOTTING OF FAN TYPE AND UNITS
!     FOR FAN PLOTTING
!
   CHARACTER UNN*41,NNTT3*45,V1*3,V2*3,V3*3 &
   &,VV1*38,B*140
!
   INTEGER COLPAS,NUNN,NNT
!
!
   CALL MY_SETCHARASPECT(1.5,1.5)
!
   IF(FANTYP.EQ.1.AND.QALTYP.EQ.0)&
   &NNTT3='YZ-PLANE TRANSVERSE ABERRATIONS'
   IF(FANTYP.EQ.1.AND.QALTYP.EQ.1)&
   &NNTT3='YZ-PLANE OPTICAL PATH DIFFERENCES'
   IF(FANTYP.EQ.1.AND.QALTYP.EQ.2)&
   &NNTT3='YZ-PLANE CHROMATIC DIFFERENCES'
   IF(FANTYP.EQ.1.AND.QALTYP.EQ.3)&
   &NNTT3='YZ-PLANE LONGITUDINAL ABERRATIONS'
!
   IF(FANTYP.EQ.2.AND.QALTYP.EQ.0)&
   &NNTT3='XZ-PLANE TRANSVERSE ABERRATIONS'
   IF(FANTYP.EQ.2.AND.QALTYP.EQ.1)&
   &NNTT3='XZ-PLANE OPTICAL PATH DIFFERENCES'
   IF(FANTYP.EQ.2.AND.QALTYP.EQ.2)&
   &NNTT3='XZ-PLANE CHROMATIC DIFFERENCES'
   IF(FANTYP.EQ.2.AND.QALTYP.EQ.3)&
   &NNTT3='XZ-PLANE LONGITUDINAL ABERRATIONS'
!
   IF(FANTYP.EQ.3.AND.QALTYP.EQ.0)&
   &NNTT3='+45 DEG. TRANSVERSE ABERRATIONS'
   IF(FANTYP.EQ.3.AND.QALTYP.EQ.1)&
   &NNTT3='+45 DEG. OPTICAL PATH DIFFERENCES'
   IF(FANTYP.EQ.3.AND.QALTYP.EQ.2)&
   &NNTT3='+45 DEG. CHROMATIC DIFFERENCES'
   IF(FANTYP.EQ.3.AND.QALTYP.EQ.3)&
   &NNTT3='+45 DEG. LONGITUDINAL ABERRATIONS'
!
   IF(FANTYP.EQ.4.AND.QALTYP.EQ.0)&
   &NNTT3='-45 DEG. TRANSVERSE ABERRATIONS'
   IF(FANTYP.EQ.4.AND.QALTYP.EQ.1)&
   &NNTT3='-45 DEG. OPTICAL PATH DIFFERENCES'
   IF(FANTYP.EQ.4.AND.QALTYP.EQ.2)&
   &NNTT3='-45 DEG. CHROMATIC DIFFERENCES'
   IF(FANTYP.EQ.4.AND.QALTYP.EQ.3)&
   &NNTT3='-45 DEG. LONGITUDINAL ABERRATIONS'
!
   IF(FANTYP.EQ.5.AND.QALTYP.EQ.0)&
   &NNTT3='XZ/YZ-PLANE TRANSVERSE ABERRATIONS'
   IF(FANTYP.EQ.5.AND.QALTYP.EQ.1)&
   &NNTT3='XZ/YZ-PLANE OPTICAL PATH DIFFERENCES'
   IF(FANTYP.EQ.5.AND.QALTYP.EQ.2)&
   &NNTT3='XZ/YZ-PLANE CHROMATIC DIFFERENCES'
   IF(FANTYP.EQ.5.AND.QALTYP.EQ.3)&
   &NNTT3='XZ/YZ-PLANE LONGITUDINAL ABERRATIONS'
!
   IF(FANTYP.EQ.6.AND.QALTYP.EQ.0)&
   &NNTT3='XZ/YZ-PLANE TRANSVERSE ABERRATIONS'
   IF(FANTYP.EQ.6.AND.QALTYP.EQ.1)&
   &NNTT3='XZ/YZ-PLANE OPTICAL PATH DIFFERENCES'
   IF(FANTYP.EQ.6.AND.QALTYP.EQ.2)&
   &NNTT3='XZ/YZ-PLANE CHROMATIC DIFFERENCES'
   IF(FANTYP.EQ.6.AND.QALTYP.EQ.3)&
   &NNTT3='XZ/YZ-PLANE LONGITUDINAL ABERRATIONS'
!
   IF(FANTYP.EQ.1.AND.QALTYP.EQ.0)&
   &NNT=31
   IF(FANTYP.EQ.1.AND.QALTYP.EQ.1)&
   &NNT=33
   IF(FANTYP.EQ.1.AND.QALTYP.EQ.2)&
   &NNT=30
   IF(FANTYP.EQ.1.AND.QALTYP.EQ.3)&
   &NNT=33
!
   IF(FANTYP.EQ.2.AND.QALTYP.EQ.0)&
   &NNT=31
   IF(FANTYP.EQ.2.AND.QALTYP.EQ.1)&
   &NNT=33
   IF(FANTYP.EQ.2.AND.QALTYP.EQ.2)&
   &NNT=30
   IF(FANTYP.EQ.2.AND.QALTYP.EQ.3)&
   &NNT=33
!
   IF(FANTYP.EQ.3.AND.QALTYP.EQ.0)&
   &NNT=31
   IF(FANTYP.EQ.3.AND.QALTYP.EQ.1)&
   &NNT=33
   IF(FANTYP.EQ.3.AND.QALTYP.EQ.2)&
   &NNT=30
   IF(FANTYP.EQ.3.AND.QALTYP.EQ.3)&
   &NNT=33
!
   IF(FANTYP.EQ.4.AND.QALTYP.EQ.0)&
   &NNT=31
   IF(FANTYP.EQ.4.AND.QALTYP.EQ.1)&
   &NNT=33
   IF(FANTYP.EQ.4.AND.QALTYP.EQ.2)&
   &NNT=30
   IF(FANTYP.EQ.4.AND.QALTYP.EQ.3)&
   &NNT=33
!
   IF(FANTYP.EQ.5.AND.QALTYP.EQ.0)&
   &NNT=34
   IF(FANTYP.EQ.5.AND.QALTYP.EQ.1)&
   &NNT=36
   IF(FANTYP.EQ.5.AND.QALTYP.EQ.2)&
   &NNT=33
   IF(FANTYP.EQ.5.AND.QALTYP.EQ.3)&
   &NNT=36
!
   IF(FANTYP.EQ.6.AND.QALTYP.EQ.0)&
   &NNT=34
   IF(FANTYP.EQ.6.AND.QALTYP.EQ.1)&
   &NNT=36
   IF(FANTYP.EQ.6.AND.QALTYP.EQ.2)&
   &NNT=33
   IF(FANTYP.EQ.6.AND.QALTYP.EQ.3)&
   &NNT=36
!
   IF(sys_mode().EQ.1.0D0.OR.sys_mode().EQ.2.0D0) THEN
!     FOCAL OR UFOCAL
      IF(sys_units().EQ.1.0D0) UNN='UNITS = in(s)'
      IF(sys_units().EQ.2.0D0) UNN='UNITS = cm(s)'
      IF(sys_units().EQ.3.0D0) UNN='UNITS = mm(s)'
      IF(sys_units().EQ.4.0D0) UNN='UNITS = meter(s)'
      IF(sys_units().EQ.1.0D0) NUNN=13
      IF(sys_units().EQ.2.0D0) NUNN=13
      IF(sys_units().EQ.3.0D0) NUNN=13
      IF(sys_units().EQ.4.0D0) NUNN=16
   ELSE
!     NOT FOCAL
   END IF
   IF(sys_mode().EQ.3.0D0.OR.sys_mode().EQ.4.0D0) THEN
!     AFOCAL OR UAFOCAL
      UNN='UNITS = radian(s)'
      NUNN=17
   ELSE
!     NOT AFOCAL
   END IF
!     IF OPD RESET ABERRATION UNITS
   IF(QALTYP.EQ.1)&
   &UNN='UNITS = WAVES AT REFERENCE WAVELENGTH'
   IF(QALTYP.EQ.1)&
   &NUNN=37
!     NOW PLOT NNTT3 ABOVE UNN JUST TO THE RIGHT OF THE WAVELENGTH
!     LEGEND
!
   WRITE(B,181) NEWOBJ
   READ(B,201) V1
   WRITE(B,181) NEWREF
   READ(B,201) V2
   WRITE(B,181) NEWIMG
   READ(B,201) V3
181 FORMAT(I3)
201 FORMAT(A3)
!
   VV1=V1//'=OBJ SURF '//V2//'=REF SURF '//V3//'=IMG SURF'

!
!     DO THE PLOTTING OF THE PLOT TYPE
!
   COLPAS=COLLBL
   CALL MY_COLTYP(COLPAS)
   CALL MY_JUSTSTRING(4100,1175,NNTT3(1:NNT),0,1,3,3)
   CALL MY_JUSTSTRING(4100,1000,UNN(1:NUNN),0,1,3,3)
   CALL MY_JUSTSTRING(4100,850,VV1(1:37),0,1,3,3)
!
!     NOW BOX THE LEGENDS OFF
!
   COLPAS=COLFRM
   CALL MY_COLTYP(COLPAS)
!     LIFT PEN, MOVE TO TOP
   CALL PAGE_PLOT(3000,1325,0,0)
!     DROP PEN, DRAW LINE
   CALL PAGE_PLOT(KDP_PAGE_W,1325,1,0)
   CALL PAGE_PLOT(3000,700,0,0)
   CALL PAGE_PLOT(KDP_PAGE_W,700,1,0)
!     LIFT PEN, RETURN TO 0,0
   CALL PAGE_PLOT(0,0,0,0)
!
   IF(.NOT.PLEXIS) PLEXIS=.TRUE.
!
   RETURN
END
! SUB FANRWV.FOR
SUBROUTINE FANRWV
   use plot_geometry
!
   use DATHGR
   use DATLEN
   use DATMAI
   use mod_system, only: sys_wavelength
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
!       THIS ROUTINE DOES THE PLOTTING OF THE REFERENCE WAVELENGTH LEGEND
!     FOR FAN PLOTTING
!
   CHARACTER NNTT1*8,NNTT2*9,VALUE*8,NNTT3*10,VALUE1*10,NNTT4*22 &
   &,NNTT11*10,NNTT12*8,NNTT10*16,B*140
!
   INTEGER COLPAS,NT1ANG,NT1SIZ
!
!
!     SET LETTER SIZE AND ANGLE
   NT1SIZ=1
   NT1ANG=0
   CALL MY_SETCHARASPECT(1.5,1.5)
!
!     DO THE PLOTTING OF THE LEGEND FOR THE REFERENCE WAVELENGTH
   NNTT4='REFERENCE WAVELENGTH'
   COLPAS=COLLBL
   CALL MY_COLTYP(COLPAS)
   CALL MY_JUSTSTRING(3200,550,NNTT4(1:20),NT1ANG,NT1SIZ,3,3)
!
!     DO THE PLOTTING OF THE LEGEND FOR THE REFERENCE WAVELENGTH
   IF(sys_wavelength(REFWV).GT.99.9D0) THEN
      IF(REFWV.GE.1.AND.REFWV.LE.5) THEN
         WRITE(B,180)REAL(sys_wavelength(REFWV))
      END IF
      IF(REFWV.GE.6.AND.REFWV.LE.10) THEN
         WRITE(B,180)REAL(sys_wavelength(REFWV))
      END IF
      READ(B,200) VALUE1
180   FORMAT(G10.4)
200   FORMAT(A10)
      NNTT3=VALUE1
      COLPAS=COLLBL
      CALL MY_COLTYP(COLPAS)
      CALL MY_JUSTSTRING(3200,350,NNTT3(1:10),NT1ANG,NT1SIZ,3,3)
   ELSE
      IF(REFWV.GE.1.AND.REFWV.LE.5) THEN
         WRITE(B,181)REAL(sys_wavelength(REFWV))
      END IF
      IF(REFWV.GE.6.AND.REFWV.LE.10) THEN
         WRITE(B,181)REAL(sys_wavelength(REFWV))
      END IF
      READ(B,201) VALUE
181   FORMAT(F8.5)
201   FORMAT(A8)
      NNTT1=VALUE
      COLPAS=COLLBL
      CALL MY_COLTYP(COLPAS)
      CALL MY_JUSTSTRING(3200,350,NNTT1(1:8),NT1ANG,NT1SIZ,3,3)
   END IF
   NNTT2='MICRON(S)'
   COLPAS=COLLBL
   CALL MY_COLTYP(COLPAS)
   CALL MY_JUSTSTRING(4200,350,NNTT2,NT1ANG,NT1SIZ,3,3)
!
   NNTT10='REL. APT. OFFSET'
   CALL MY_JUSTSTRING(5350,550,NNTT10(1:16),NT1ANG,NT1SIZ,3,3)
!
   IF(FANOFF.GT.99.9D0) THEN
      WRITE(B,180)REAL(FANOFF)
      READ(B,200) VALUE1
      NNTT11=VALUE1
      CALL MY_JUSTSTRING(5350,350,NNTT11(1:10),NT1ANG,NT1SIZ,3,3)
   ELSE
      WRITE(B,181)REAL(FANOFF)
      READ(B,201) VALUE
      NNTT12=VALUE
      COLPAS=COLLBL
      CALL MY_COLTYP(COLPAS)
      CALL MY_JUSTSTRING(5350,350,NNTT12(1:8),NT1ANG,NT1SIZ,3,3)
   END IF
!
   COLPAS=COLFRM
   CALL MY_COLTYP(COLPAS)
!     NOW BOX THE LEGENDS OFF
!
!     LIFT PEN, MOVE TO TOP
   CALL PAGE_PLOT(3000,700,0,0)
!     DROP PEN, DRAW LINE
   CALL PAGE_PLOT(5200,700,1,0)
   CALL PAGE_PLOT(5200,250,1,0)
   CALL PAGE_PLOT(3000,700,0,0)
!     DROP PEN, DRAW LINE
   CALL PAGE_PLOT(KDP_PAGE_W,700,1,0)
!     LIFT PEN, RETURN TO 0,0
   CALL PAGE_PLOT(0,0,0,0)
!
   IF(.NOT.PLEXIS) PLEXIS=.TRUE.
!
   RETURN
END
! SUB FANLI.FOR
SUBROUTINE FANLI
   use plot_geometry
!
   use DATHGR
   use DATLEN
   use DATMAI
   use iso_fortran_env, only: real64
   IMPLICIT NONE
!
!       THIS ROUTINE DOES THE PLOTTING OF THE LENS IDENTIFIER "LI"
!     FOR FAN PLOTTING
!
   CHARACTER DTY*10,TMY*8,BL20*20,BLNOTE*80,NNTT1*80
!
   INTEGER COLPAS,NT1ANG,NT1SIZ,IIX,IIY,IIUD
!
!
   BL20='                    '
   BLNOTE=BL20//BL20//BL20//BL20
!
!     MOVE TO THE STARTING POSITION FOR THE LI
!
   CALL PAGE_PLOT(50,100,0,0)

!     DO THE PLOTTING OF THE LENS IDENTIFIER
   IF(STMPT) CALL MYTIME(TMY)
   IF(STMPD) CALL MYDATE(DTY)
   IF(.NOT.STMPT.AND..NOT.STMPD) NNTT1=LI
   IF(STMPT.AND.STMPD) NNTT1=TMY//' '//DTY//LI
   IF(STMPT.AND..NOT.STMPD) NNTT1=TMY//' '//LI
   IF(.NOT.STMPT.AND.STMPD) NNTT1=DTY//LI
   IF(NNTT1.NE.BLNOTE) THEN
      CALL MY_SETCHARASPECT(1.5,1.5)
      COLPAS=COLLBL
      CALL MY_COLTYP(COLPAS)
      CALL MY_JUSTSTRING(50,100,NNTT1(1:80),0,1,3,3)

      COLPAS=COLFRM
      CALL MY_COLTYP(COLPAS)
!     LIFT PEN, MOVE TO TOP
      CALL PAGE_PLOT(0,250,0,0)
!     DROP PEN, DRAW LINE
      CALL PAGE_PLOT(KDP_PAGE_W,250,1,0)
!     LIFT PEN, RETURN TO 0,0
      CALL PAGE_PLOT(0,0,0,0)
      IF(.NOT.PLEXIS) PLEXIS=.TRUE.
   ELSE
!     LI BLANK, NOT ACTION
   END IF
!
   RETURN
END
